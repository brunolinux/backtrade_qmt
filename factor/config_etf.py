def getETFFundsInfo() -> pd.DataFrame:
    out = []
    for key, item in FundsDict.items():
        one = {
            "symbol": key, 
            "name": item[0],
            "start_date": item[1], 
            "is_t0": item[2], 
            "is_lof": item[3],
        }
        out.append(one)

    df_out = pd.DataFrame(out)
    df_out["start_date"] = pd.to_datetime(df_out["start_date"], format="%Y-%m-%d")
    df_out.set_index("symbol", inplace=True)
    return df_out

